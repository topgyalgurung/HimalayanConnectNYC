
import "./globals.css";

import type { Metadata } from "next";
import { Inter } from "next/font/google";
import { Toaster } from "react-hot-toast";
import { Analytics } from "@vercel/analytics/next";
import { SpeedInsights } from '@vercel/speed-insights/next';
import { NextIntlClientProvider } from "next-intl";
import { getLocale, getMessages } from "next-intl/server";

import { UserProvider } from "@/app/context/UserProvider";
import NavMenu from "@/app/ui/NavMenu";

// recommended to use to ensure styles appended to head and not rendering in the body
import { AppRouterCacheProvider } from "@mui/material-nextjs/v15-appRouter";

const inter = Inter({ subsets: ["latin"] });

export const metadata: Metadata = {
  title: "Himalayan Connect NYC",
  description: "Generated by create next app",
};

export default async function RootLayout({
  children,
}: Readonly<{
  children: React.ReactNode;
}>) {
  // Locale comes from the "locale" cookie (see src/i18n/request.ts); the
  // provider makes translations available to all client components.
  const locale = await getLocale();
  const messages = await getMessages();

  return (
    <html lang={locale} data-theme="winter">
      <head>
        <meta
          name="viewport"
          content="width=device-width, initial-scale=1.0, maximum-scale=1.0, user-scalable=no"
        />
      </head>
      <body
        className={`${inter.className} min-h-screen flex flex-col lg:overflow-hidden`}
      >
        <NextIntlClientProvider locale={locale} messages={messages}>
        <UserProvider>
          <AppRouterCacheProvider>
              <NavMenu />
              <Toaster
                position="top-center"
                toastOptions={{ duration: 2000 }}
              />
              <main className="flex-grow pt-4 md:pt-6 lg:pt-2 overflow-y-auto">
                <div className="px-2 sm:px-6 [&>*:first-child]:!px-0 [&>*:first-child]:!mx-0">
                  {children}
                  <Analytics/>
                   <SpeedInsights />
                </div>
              </main>

              {/* Footer component commented out for future implementation */}
              {/* <footer className="bg-slate-900 text-white p-4 text-center shadow-md h-[60px] flex-none">
              © Himalayan Connect NYC
            </footer> */}
            {/* </ThemeProvider> */}
          </AppRouterCacheProvider>
        </UserProvider>
        </NextIntlClientProvider>
      </body>
    </html>
  );
}
